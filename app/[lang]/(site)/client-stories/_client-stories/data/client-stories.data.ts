export function getAllClientStories(): ClientStoryDetail[] {
  return clientStoriesData;
}

export function getClientStoryBySlug(slug: string): ClientStoryDetail | undefined {
  return clientStoriesData.find((s) => s.slug === slug);
}

export function getFeaturedClientStories(): ClientStoryDetail[] {
  return clientStoriesData
    .filter((s) => s.featured)
    .sort((a, b) => (a.featuredOrder || 99) - (b.featuredOrder || 99));
}

export function getRelatedClientStories(currentSlug: string, count = 3): ClientStoryDetail[] {
  const current = getClientStoryBySlug(currentSlug);
  if (!current) return clientStoriesData.slice(0, count);

  // First try relatedSlugs
  if (current.relatedSlugs && current.relatedSlugs.length > 0) {
    const related = current.relatedSlugs
      .map((slug) => getClientStoryBySlug(slug))
      .filter((s): s is ClientStoryDetail => Boolean(s));
    if (related.length >= count) return related.slice(0, count);
  }

  // Fallback to same category, then any
  const sameCategory = clientStoriesData.filter(
    (s) => s.slug !== currentSlug && s.categorySlug === current.categorySlug
  );
  const others = clientStoriesData.filter(
    (s) => s.slug !== currentSlug && s.categorySlug !== current.categorySlug
  );

  return [...sameCategory, ...others].slice(0, count);
}
